#!/usr/bin/env node
// Copies the generated `bindings/wasm/pkg` artifact into `src/generated/nidus-wasm/`
// (nidus-7pj). NOT public/: Vite refuses a source import of a public/ file, in dev and
// in build, and the glue's `new URL(..., import.meta.url)` needs bundler processing.
import { existsSync, mkdirSync, copyFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const pkgDir = join(scriptDir, "..", "..", "bindings", "wasm", "pkg");
const outDir = join(scriptDir, "..", "src", "generated", "nidus-wasm");
const required = process.env.NIDUS_WASM_REQUIRED === "1";

const files = ["nidus_wasm.js", "nidus_wasm.d.ts", "nidus_wasm_bg.wasm", "nidus_wasm_bg.wasm.d.ts"];

// The worker imports this path with a literal specifier so Vite emits the payload, which
// means the file must exist even with no artifact built. A stub that throws keeps the
// terminal on its static fallback instead of failing the whole build.
const STUB = `// Generated by docs/scripts/copy-wasm.mjs: no wasm artifact was built.
// Run \`just build-wasm-binding\` to replace this with the real binding.
const missing = () => {
  throw new Error("nidus wasm artifact not built (run: just build-wasm-binding)");
};
export default missing;
export const NidusHandle = { open: missing, open_in_memory: missing };
export const init_opfs_pool = missing;
export const grow_opfs_pool = missing;
`;

mkdirSync(outDir, { recursive: true });

if (!existsSync(pkgDir)) {
  const msg = "bindings/wasm/pkg is absent. Run `just build-wasm-binding` to generate it.";
  if (required) {
    console.error(`error: ${msg}`);
    process.exit(1);
  }
  writeFileSync(join(outDir, "nidus_wasm.js"), STUB);
  console.log(`note: ${msg} Wrote a stub; the live terminal stays on its static fallback.`);
  process.exit(0);
}

for (const file of files) {
  copyFileSync(join(pkgDir, file), join(outDir, file));
}
console.log(`copied ${files.length} wasm artifact files into src/generated/nidus-wasm/`);
